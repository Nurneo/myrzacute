/**
 * Get a push message by type.
 * Uses date-based deterministic index (same message for same day) or random.
 */
export function getPushMessage(
  type: 'midnight' | 'midday' | 'secret',
  explicitIndex?: number
): PushMessage {
  const pool =
    type === 'midnight'
      ? MIDNIGHT_MESSAGES
      : type === 'midday'
      ? MIDDAY_MESSAGES
      : SECRET_MESSAGES;

  let index: number;
  if (explicitIndex !== undefined) {
    index = Math.abs(explicitIndex) % pool.length;
  } else {
    // Deterministic by date string so same day = same message
    const dateStr = new Date().toISOString().split('T')[0]; // e.g. '2026-07-30'
    const charSum = dateStr.split('').reduce((acc, ch) => acc + ch.charCodeAt(0), 0);
    index = charSum % pool.length;
  }

  return pool[index];
}
