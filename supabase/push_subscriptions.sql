-- Run this script in your Supabase SQL Editor (https://supabase.com/dashboard/project/_/sql)
-- to ensure the push_subscriptions table and permissions are ready for Web Push.

CREATE TABLE IF NOT EXISTS public.push_subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    endpoint TEXT NOT NULL UNIQUE,
    keys_p256dh TEXT NOT NULL,
    keys_auth TEXT NOT NULL,
    user_agent TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- Unique index on endpoint for fast upserts
CREATE UNIQUE INDEX IF NOT EXISTS push_subscriptions_endpoint_idx ON public.push_subscriptions (endpoint);

-- Enable Row Level Security (RLS)
ALTER TABLE public.push_subscriptions ENABLE ROW LEVEL SECURITY;

-- Drop existing policies if any to avoid errors on replay
DROP POLICY IF EXISTS "Allow public select on push_subscriptions" ON public.push_subscriptions;
DROP POLICY IF EXISTS "Allow public insert on push_subscriptions" ON public.push_subscriptions;
DROP POLICY IF EXISTS "Allow public update on push_subscriptions" ON public.push_subscriptions;
DROP POLICY IF EXISTS "Allow public delete on push_subscriptions" ON public.push_subscriptions;

-- Allow anon and authenticated roles to read, insert, update and delete
CREATE POLICY "Allow public select on push_subscriptions"
    ON public.push_subscriptions FOR SELECT
    TO anon, authenticated
    USING (true);

CREATE POLICY "Allow public insert on push_subscriptions"
    ON public.push_subscriptions FOR INSERT
    TO anon, authenticated
    WITH CHECK (true);

CREATE POLICY "Allow public update on push_subscriptions"
    ON public.push_subscriptions FOR UPDATE
    TO anon, authenticated
    USING (true)
    WITH CHECK (true);

CREATE POLICY "Allow public delete on push_subscriptions"
    ON public.push_subscriptions FOR DELETE
    TO anon, authenticated
    USING (true);
